import Editor from "@monaco-editor/react";
import { useQuery } from "@tanstack/react-query";
import { useEffect, useRef, useState } from "react";
import { useSearchParams } from "react-router-dom";
import { Bar, BarChart, CartesianGrid, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { Card, Field, Notice, Page, QueryState, inputClass } from "../components/ui";
import { api } from "../lib/api";

type LogResult = {
  environment_label?: string;
  status: string;
  message?: string;
  searched?: string[];
  record_source?: string;
  syslog_count?: number;
  activity?: Array<{ at?: string; kind?: string; text?: string }>;
  logs: Array<{ id?: string; timestamp: string; level: string; message: string; signature?: string; correlation_id?: string }>;
  frequency: Array<{ bucket: string; errors: number; warnings: number; info: number }>;
  baseline?: { available?: boolean; incident_window_errors?: number; baseline_errors?: number | null };
  groups?: Array<{ signature: string; count: number }>;
};

export function Logs() {
  const [params] = useSearchParams();
  const incidents = useQuery({ queryKey: ["incidents", "logs"], queryFn: () => api<{ items: Array<{ id: string; number: string; source: string }> }>("/incidents?limit=50") });
  const [incidentId, setIncidentId] = useState(params.get("incident") || "");
  const [signature, setSignature] = useState("");
  const [correlation, setCorrelation] = useState("");
  const [q, setQ] = useState("");
  const [selected, setSelected] = useState<LogResult["logs"][number] | null>(null);
  const inspectorRef = useRef<HTMLDivElement>(null);
  const chosen = incidentId || incidents.data?.items[0]?.id || "";
  const source = incidents.data?.items.find((item) => item.id === chosen)?.source;
  const connector = source === "servicenow" ? "servicenow" : "easidoc";
  const logs = useQuery({
    queryKey: ["logs", chosen, connector, signature, correlation, q],
    enabled: Boolean(chosen),
    queryFn: () => api<LogResult>(`/logs?connector=${connector}&incident_id=${chosen}&signature=${encodeURIComponent(signature)}&correlation_id=${encodeURIComponent(correlation)}&q=${encodeURIComponent(q)}`),
  });
  useEffect(() => {
    const node = inspectorRef.current;
    const scroller = node?.closest("main");
    if (!node || !scroller || !selected) return;
    const top = node.getBoundingClientRect().top - scroller.getBoundingClientRect().top + scroller.scrollTop - 16;
    scroller.scrollTop = Math.max(0, top);
  }, [selected]);
  const rows = logs.data?.logs ?? [];
  const fromWorkNote = logs.data?.record_source === "work_note";
  const chart = (logs.data?.frequency ?? []).map((item) => ({ name: item.bucket.slice(5, 16) || item.bucket, errors: item.errors, warnings: item.warnings, notes: item.info }));

  return (
    <Page title="Log Intelligence" lede="ServiceNow incidents read live syslog. Easidoc incidents read the simulator log store.">
      <Notice tone={connector === "servicenow" ? "info" : "warn"}>
        {connector === "servicenow"
          ? logs.data?.message || "ServiceNow syslog is read for identifiers on the selected incident."
          : `${logs.data?.environment_label ?? "EASIDOC — SIMULATED APPLICATION"}. These lines are generated by the digital twin.`}
      </Notice>
      <div className="grid gap-3 md:grid-cols-4">
        <Field label="Incident">
          <select className={inputClass} value={chosen} onChange={(event) => setIncidentId(event.target.value)}>
            {(incidents.data?.items ?? []).map((item) => <option key={item.id} value={item.id}>{item.number}</option>)}
          </select>
        </Field>
        <Field label="Error signature"><input className={inputClass} value={signature} onChange={(event) => setSignature(event.target.value)} placeholder="REVIEW_PARTICIPANT_NOT_FOUND" /></Field>
        <Field label="Correlation ID"><input className={inputClass} value={correlation} onChange={(event) => setCorrelation(event.target.value)} /></Field>
        <Field label="Message search"><input className={inputClass} value={q} onChange={(event) => setQ(event.target.value)} /></Field>
      </div>
      <QueryState loading={logs.isLoading} error={logs.error}>
        <div className="grid items-start gap-4 lg:grid-cols-[0.9fr_1.1fr]">
          <div className="space-y-4">
          <Card>
            <h2 className="text-sm font-medium">Error frequency</h2>
            <div className="mt-3 h-52">
              <ResponsiveContainer>
                <BarChart data={chart}>
                  <CartesianGrid stroke="#e4e9ef" vertical={false} />
                  <XAxis dataKey="name" tick={{ fontSize: 11, fill: "#5d6b7c" }} />
                  <YAxis allowDecimals={false} tick={{ fontSize: 12, fill: "#5d6b7c" }} />
                  <Tooltip />
                  <Bar dataKey="errors" stackId="level" fill="#1d1d1f" radius={[0, 0, 0, 0]} />
                  <Bar dataKey="warnings" stackId="level" fill="#6e6e73" />
                  <Bar dataKey="notes" stackId="level" fill="#d2d2d7" radius={[6, 6, 0, 0]} />
                </BarChart>
              </ResponsiveContainer>
            </div>
            <p className="mt-2 text-xs text-mist">
              {fromWorkNote
                ? `${logs.data?.baseline?.incident_window_errors ?? 0} error in the work note. ServiceNow syslog matched ${logs.data?.syslog_count ?? 0} lines for ${logs.data?.searched?.join(", ") || "this incident"}.`
                : `Incident-window errors ${logs.data?.baseline?.incident_window_errors ?? 0}. Baseline ${logs.data?.baseline?.baseline_errors ?? "not compared"}.`}
            </p>
          </Card>
          <div ref={inspectorRef}>
          <Card>
            <h2 className="mb-2 text-sm font-medium">Evidence inspector</h2>
            {selected ? (
              <div className="h-64 overflow-hidden rounded-xl border border-line">
                <Editor height="100%" defaultLanguage="json" value={JSON.stringify(selected, null, 2)} options={{ readOnly: true, minimap: { enabled: false }, fontSize: 12, scrollBeyondLastLine: false }} />
              </div>
            ) : (
              <p className="text-sm text-mist">Select a log line to inspect it.</p>
            )}
          </Card>
          </div>
          </div>
          <Card>
            {fromWorkNote ? <p className="border-b border-line pb-2 text-sm text-mist">No syslog line matched {logs.data?.searched?.join(", ") || "this incident"}. The lines below are the work note on the incident.</p> : null}
            {rows.map((row) => (
              <button key={row.id} className="block w-full border-b border-line py-2 text-left text-sm" onClick={() => setSelected(row)}>
                <span className="text-xs text-mist">{row.timestamp} · {row.level} · {row.signature || "no signature"}</span>
                <span className="block">{row.message}</span>
              </button>
            ))}
            {!rows.length ? <p className="text-sm text-mist">{connector === "servicenow" ? `No syslog line matched ${logs.data?.searched?.join(", ") || "this incident"}.` : "No log lines in this window."}</p> : null}
          </Card>
        </div>
      </QueryState>
    </Page>
  );
}
